# ---------------------------------------------------------------------------
# FrequencyDatabase Class
# ---------------------------------------------------------------------------

class FrequencyDatabase:
    """
    24-locus allele frequency database with NRC II Rule 4.1 minimum floor
    and Balding-Nichols NRC II Rec 4.10b theta-corrected genotype probabilities.
    """

    def __init__(
        self,
        default_population: str = "Caucasian",
        min_frequency: float = DEFAULT_MIN_FREQUENCY,
    ):
        self.default_population = default_population
        self.min_frequency = min_frequency

    @property
    def supported_populations(self) -> list:
        return list(POPULATION_FREQUENCIES.keys())

    # ── Allele Frequency Lookup ───────────────────────────────────────────

    def get_frequency(
        self,
        locus_name: str,
        allele_value: float,
        population: Optional[str] = None,
    ) -> float:
        """Returns bounded allele frequency enforcing NRC II Rule 4.1 floor."""
        pop = population or self.default_population
        pop_db = POPULATION_FREQUENCIES.get(pop, POPULATION_FREQUENCIES["Caucasian"])
        locus_db = pop_db.get(locus_name.upper(), {})
        freq = locus_db.get(allele_value, self.min_frequency)
        return max(freq, self.min_frequency)

    # ── Balding-Nichols 4-State Genotype Probabilities ────────────────────

    def calculate_genotype_probability(
        self,
        locus_name: str,
        allele1: float,
        allele2: float,
        theta: float = DEFAULT_THETA,
        population: Optional[str] = None,
    ) -> float:
        """
        NRC II Recommendation 4.10b — 2-state Balding-Nichols P(G | theta).

        Unconditional genotype probability (H2 denominator for single-source LR):
          Homozygote: [2θ+(1-θ)p_i][θ+(1-θ)p_i] / [(1+θ)(1+2θ)]   ← NRC II corrected
          Heterozygote: 2[θ+(1-θ)p_i][θ+(1-θ)p_j] / [(1+θ)(1+2θ)]
        """
        p_i = self.get_frequency(locus_name, allele1, population)
        p_j = self.get_frequency(locus_name, allele2, population)
        denom = (1.0 + theta) * (1.0 + 2.0 * theta)

        if allele1 == allele2:
            # Homozygous: [2θ+(1-θ)p_i][θ+(1-θ)p_i] / den  (NRC II p. 114)
            num = (2.0 * theta + (1.0 - theta) * p_i) * (theta + (1.0 - theta) * p_i)
        else:
            # Heterozygous: 2[θ+(1-θ)p_i][θ+(1-θ)p_j] / den
            num = 2.0 * (theta + (1.0 - theta) * p_i) * (theta + (1.0 - theta) * p_j)

        return num / denom

    def calculate_conditional_genotype_probability(
        self,
        locus_name: str,
        evidence_allele1: float,
        evidence_allele2: float,
        suspect_allele1: float,
        suspect_allele2: float,
        theta: float = DEFAULT_THETA,
        population: Optional[str] = None,
    ) -> float:
        """
        Balding-Nichols 4-state CONDITIONAL probability P(E_genotype | S_genotype, θ).

        Implements all 4 matching scenarios from Pillar 1 §1.2:
          State 1 — Full homozygous match (A_i A_i | A_i A_i)
          State 2 — Full heterozygous match (A_i A_j | A_i A_j)
          State 3 — Partial match, 1 shared allele (A_i A_j | A_i A_k)
          State 4 — Zero shared alleles (A_i A_j | A_k A_l)
        """
        e_alleles = frozenset([evidence_allele1, evidence_allele2])
        s_alleles = frozenset([suspect_allele1, suspect_allele2])
        shared = e_alleles & s_alleles
        n_shared = len(shared)

        denom = (1.0 + theta) * (1.0 + 2.0 * theta)

        # State 1: Full homozygous match A_i A_i | A_i A_i
        if (evidence_allele1 == evidence_allele2 == suspect_allele1 == suspect_allele2):
            p_i = self.get_frequency(locus_name, evidence_allele1, population)
            num = (2.0 * theta + (1.0 - theta) * p_i) * (3.0 * theta + (1.0 - theta) * p_i)
            return num / denom

        # State 2: Full heterozygous match A_i A_j | A_i A_j (same allele pair)
        if (n_shared == 2 and
                evidence_allele1 != evidence_allele2 and
                suspect_allele1 != suspect_allele2):
            e_sorted = tuple(sorted(e_alleles))
            p_i = self.get_frequency(locus_name, e_sorted[0], population)
            p_j = self.get_frequency(locus_name, e_sorted[1], population)
            num = 2.0 * (theta + (1.0 - theta) * p_i) * (theta + (1.0 - theta) * p_j)
            return num / denom

        # State 3: One shared allele A_i A_j | A_i A_k
        if n_shared == 1:
            shared_a = list(shared)[0]
            unshared_e = list(e_alleles - shared)[0] if (e_alleles - shared) else shared_a
            p_i = self.get_frequency(locus_name, shared_a, population)
            p_j = self.get_frequency(locus_name, unshared_e, population)
            num = (theta + (1.0 - theta) * p_i) * ((1.0 - theta) * p_j)
            return num / denom

        # State 4: Zero shared alleles A_i A_j | A_k A_l
        e_sorted = tuple(sorted(e_alleles))
        p_i = self.get_frequency(locus_name, e_sorted[0], population)
        p_j = self.get_frequency(locus_name, e_sorted[1] if len(e_sorted) > 1 else e_sorted[0], population)
        num = 2.0 * ((1.0 - theta) * p_i) * ((1.0 - theta) * p_j)
        return num / denom
